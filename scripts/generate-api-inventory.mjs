#!/usr/bin/env node
// scripts/generate-api-inventory.mjs
//
// Phase 7 -- API Platform. Generates docs/API_PLATFORM_INVENTORY.md by
// scanning the real src/pages/api file tree -- an honest, always-current
// inventory (regenerate any time the API surface changes) rather than a
// hand-maintained doc that drifts from reality.

import fs from "node:fs";
import path from "node:path";

const API_DIR = path.join(process.cwd(), "src", "pages", "api");
const OUT_FILE = path.join(process.cwd(), "docs", "API_PLATFORM_INVENTORY.md");

function walk(dir, base = "") {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const routes = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    const rel = path.join(base, entry.name);
    if (entry.isDirectory()) {
      routes.push(...walk(full, rel));
    } else if (/\.(ts|js)$/.test(entry.name) && !entry.name.endsWith(".d.ts")) {
      routes.push({ file: full, rel });
    }
  }
  return routes;
}

function toRoute(rel) {
  const withoutExt = rel.replace(/\.(ts|js)$/, "");
  const segments = withoutExt.split(path.sep).map((seg) => {
    if (seg.startsWith("[...") && seg.endsWith("]")) {
      return `*${seg.slice(4, -1)}`;
    }
    if (seg.startsWith("[") && seg.endsWith("]")) {
      return `:${seg.slice(1, -1)}`;
    }
    return seg;
  });
  const last = segments[segments.length - 1];
  if (last === "index") segments.pop();
  return `/api/${segments.join("/")}`;
}

function detectMethods(source) {
  const methods = new Set();
  const methodRegex =
    /req\.method\s*(?:===|!==|==)\s*["'](GET|POST|PUT|PATCH|DELETE)["']/g;
  let m;
  while ((m = methodRegex.exec(source))) methods.add(m[1]);
  if (methods.size === 0)
    methods.add("GET/POST (unrestricted or method-agnostic)");
  return Array.from(methods).sort();
}

function detectAuth(source) {
  if (source.includes("requireAdminFromRequest")) return "admin";
  if (source.includes("getNetworkSession")) return "session (cookie or Bearer)";
  if (source.includes("session_token")) return "session (cookie)";
  return "public / unauthenticated";
}

function detectRateLimit(source) {
  return source.includes("hitApiRateLimit") ? "yes" : "no";
}

const routes = walk(API_DIR)
  .map(({ file, rel }) => {
    const source = fs.readFileSync(file, "utf8");
    return {
      route: toRoute(rel),
      methods: detectMethods(source),
      auth: detectAuth(source),
      rateLimited: detectRateLimit(source),
      file: path.relative(process.cwd(), file),
    };
  })
  .sort((a, b) => a.route.localeCompare(b.route));

const authCounts = routes.reduce((acc, r) => {
  acc[r.auth] = (acc[r.auth] || 0) + 1;
  return acc;
}, {});

const lines = [];
lines.push("# BWE API Platform Inventory");
lines.push("");
lines.push(
  `Auto-generated by \`node scripts/generate-api-inventory.mjs\` -- do not hand-edit. Regenerate after any API change. Generated at ${new Date().toISOString()}.`,
);
lines.push("");
lines.push(`Total routes: ${routes.length}`);
lines.push("");
lines.push("By auth model:");
for (const [auth, count] of Object.entries(authCounts).sort(
  (a, b) => b[1] - a[1],
)) {
  lines.push(`- ${auth}: ${count}`);
}
lines.push("");
lines.push("| Route | Methods | Auth | Rate limited | File |");
lines.push("|---|---|---|---|---|");
for (const r of routes) {
  lines.push(
    `| \`${r.route}\` | ${r.methods.join(", ")} | ${r.auth} | ${r.rateLimited} | \`${r.file}\` |`,
  );
}
lines.push("");

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, lines.join("\n"));
console.log(
  `Wrote ${routes.length} routes to ${path.relative(process.cwd(), OUT_FILE)}`,
);
